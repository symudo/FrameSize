export function resolveLocale(setting: LanguageSetting): 'zh' | 'en' {
  if (setting === 'zh' || setting === 'en') return setting;
  const lang = typeof navigator !== 'undefined' ? navigator.language : 'en';
  return /^zh\b/i.test(lang) ? 'zh' : 'en';
}

export function createTranslator(setting: LanguageSetting): (key: I18nKey) => string {
  const locale = resolveLocale(setting);
  const dict = locale === 'zh' ? ZH_MESSAGES : EN_MESSAGES;
  return (key: I18nKey) => dict[key];
}
